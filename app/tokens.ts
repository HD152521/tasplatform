/**
 * 디자인 토큰 — 이 앱의 모든 색·글자·간격이 여기서 나온다.
 *
 * ## 방향: 운영 콘솔 (Swiss / International)
 *
 * 이건 마케팅 페이지가 아니라 **하루 종일 보는 사내 데이터 도구**다. SR 목록·달력·
 * 대시보드가 전부 "몇 건이 있고 그중 무엇이 내 차례인가" 를 읽는 화면이다. 그래서
 * 다음을 지킨다.
 *
 *   - **구획은 1px 헤어라인으로.** 그림자는 진짜 떠 있는 것(드롭다운·모달)에만 쓴다.
 *     카드마다 그림자를 깔면 표가 울퉁불퉁해지고 눈이 줄을 못 따라간다.
 *   - **강조색은 상호작용에만.** 선택·링크·활성 탭. 장식으로 쓰지 않는다. 색이
 *     의미를 잃으면 "빨간 건 내 차례" 라는 규칙이 무너진다.
 *   - **숫자는 전부 tabular.** 건수·날짜가 세로로 흔들리면 비교가 안 된다.
 *   - **그라데이션·글래스 없음.** 이 화면에서 깊이가 뜻하는 것이 없다.
 *
 * ## 왜 토큰 파일을 따로 두나
 *
 * 전에는 `app/ui.tsx` 에 색만 있었고, 글자 크기·간격은 888곳의 인라인 style 에 손으로
 * 적혀 있었다(실측). 그래서 글자 크기가 **14종**(`12.5`·`11.5`·`13.5`·`10.5` 같은
 * 반 픽셀 4종 포함), padding 조합이 40종 이상이었다. 위계가 아니라 잡음이다.
 *
 * 값을 고를 자유를 없애는 것이 이 파일의 일이다. 쓰는 쪽은 **스케일에서 고른다.**
 */

